import Foundation
import Testing
@testable import VapeCalcCore

private struct FixtureCase: Decodable {
    struct Input: Decodable {
        struct Flavour: Decodable {
            let name: String
            let amount: Double
            let vg: Bool
        }
        let pg: Double
        let amount: Double
        let nic_strength: Double
        let nic_vg: Bool
        let nic_amount: Double
        let flavours: [Flavour]
    }
    struct Row: Decodable {
        let name: String
        let ml: Double
        let percent: Double
    }
    struct Expected: Decodable {
        let rows: [Row]
        let totalMl: Double
        let isValid: Bool
    }
    let input: Input
    let expected: Expected
}

private func loadFixtures() throws -> [FixtureCase] {
    let url = URL(fileURLWithPath: #filePath)
        .deletingLastPathComponent()
        .appendingPathComponent("Fixtures/reference_cases.json")
    return try JSONDecoder().decode([FixtureCase].self, from: Data(contentsOf: url))
}

/// The fixtures were generated by running the elsmoke.com.ua calculator's JavaScript (minus the
/// water step), so any drift between our volume formulas and the reference shows up here.
@Test func matchesReferenceImplementation() throws {
    for (index, fixture) in try loadFixtures().enumerated() {
        let input = RecipeInput(
            pgPercent: fixture.input.pg,
            volumeMl: fixture.input.amount,
            nicBaseStrength: fixture.input.nic_strength,
            nicBaseCarrier: fixture.input.nic_vg ? .vg : .pg,
            nicotineMgMl: fixture.input.nic_amount,
            flavours: fixture.input.flavours.map {
                Flavour(name: $0.name, percent: $0.amount, carrier: $0.vg ? .vg : .pg)
            }
        )
        let result = RecipeCalculator.calculate(input)

        #expect(result.rows.count == fixture.expected.rows.count, "case \(index): row count")
        #expect(result.totalMl == fixture.expected.totalMl, "case \(index): total ml")
        #expect(result.isValid == fixture.expected.isValid, "case \(index): validity")

        for (row, expected) in zip(result.rows, fixture.expected.rows) {
            #expect(abs(row.ml - expected.ml) < 0.005, "case \(index) \(expected.name): ml \(row.ml) != \(expected.ml)")
            #expect(abs(row.percent - expected.percent) < 0.005, "case \(index) \(expected.name): percent")
        }
    }
}

@Test func defaultRecipeSplitsFiftyFifty() {
    let result = RecipeCalculator.calculate(RecipeInput())
    #expect(result.rows[0].ml == 12.6)
    #expect(result.rows[1].ml == 15)
    #expect(result.rows[2].ml == 0.9)
    #expect(result.totalMl == 30)
    #expect(result.isValid)
}

@Test func weighsEachComponentByCarrierDensity() {
    let result = RecipeCalculator.calculate(RecipeInput())
    #expect(result.rows[0].grams == 13.05)   // 12.6 ml PG * 1.036
    #expect(result.rows[1].grams == 18.92)   // 15 ml VG * 1.261
    #expect(result.rows[2].grams == 0.93)    // 0.9 ml PG-based nicotine base
    #expect(result.rows[3].grams == 1.55)    // 1.5 ml PG-based flavour
    #expect(result.totalGrams == 34.45)
}

@Test func vgCarriersWeighMoreThanPgOnes() {
    let pgBased = RecipeCalculator.calculate(
        RecipeInput(pgPercent: 100, nicBaseCarrier: .pg, flavours: [Flavour(name: "F", percent: 10, carrier: .pg)])
    )
    let vgBased = RecipeCalculator.calculate(
        RecipeInput(pgPercent: 0, nicBaseCarrier: .vg, flavours: [Flavour(name: "F", percent: 10, carrier: .vg)])
    )
    #expect(pgBased.totalMl == vgBased.totalMl)
    #expect(pgBased.totalGrams == 31.08)   // 30 ml * 1.036
    #expect(vgBased.totalGrams == 37.82)   // 30 ml of VG, a hundredth lost to per-row rounding
}

@Test func negativeCarrierIsInvalid() {
    let input = RecipeInput(
        pgPercent: 5,
        nicBaseStrength: 100,
        nicotineMgMl: 50,
        flavours: [Flavour(name: "F", percent: 25, carrier: .pg)]
    )
    #expect(RecipeCalculator.calculate(input).isValid == false)
}
